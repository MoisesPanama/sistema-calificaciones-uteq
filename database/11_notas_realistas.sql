-- Recalcular promedios en matricula_materias
UPDATE matricula_materias mm
SET promedio = subq.nuevo_promedio,
    estado = CASE 
        WHEN subq.nuevo_promedio IS NULL THEN 'sin_notas'
        WHEN subq.nuevo_promedio >= 7 THEN 'aprobado'
        ELSE 'reprobado'
    END
FROM (
    SELECT mm2.id_detalle,
           ROUND(SUM(c.valor * te.peso) / NULLIF(SUM(te.peso), 0), 2) AS nuevo_promedio
    FROM matricula_materias mm2
    JOIN matriculas m ON m.id_matricula = mm2.id_matricula
    JOIN calificaciones c ON c.id_estudiante = m.id_estudiante 
        AND c.id_materia = mm2.id_materia 
        AND c.id_periodo = m.id_periodo
    JOIN tipos_evaluacion te ON te.id_tipo_evaluacion = c.id_tipo_evaluacion
    GROUP BY mm2.id_detalle
) subq
WHERE mm.id_detalle = subq.id_detalle;
